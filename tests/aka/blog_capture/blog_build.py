import base64, io, os
from PIL import Image
def b64(path, scale=1, fmt='PNG'):
    im = Image.open(path).convert('RGB')
    if scale != 1: im = im.resize((im.width*scale, im.height*scale), Image.NEAREST)
    bio = io.BytesIO(); im.save(bio, fmt, optimize=True) if fmt=='PNG' else im.save(bio, fmt, quality=88)
    return f'data:image/{fmt.lower()};base64,' + base64.b64encode(bio.getvalue()).decode()
